def test_all_catalog_files_are_in_paper_suite_or_fibonacci(examples):
    import importlib.util
    from pathlib import Path
    path=Path(__file__).resolve().parents[1]/'scripts/validate_papers.py'
    spec=importlib.util.spec_from_file_location('references',path)
    mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    reference_cases=list(mod.references())
    names={row[0] for row in reference_cases}|{'fibonacci'}
    assert names=={f.stem for f in examples.glob('*.json')}
    runner_path=Path(__file__).resolve().parents[1]/'run_examples.py'
    spec=importlib.util.spec_from_file_location('example_runner',runner_path)
    runner=importlib.util.module_from_spec(spec);spec.loader.exec_module(runner)
    example_cases=[(name,group,lattice,tuple(iwps))
                   for name,groups in runner.example_groups() for group in groups
                   for lattice,iwps in runner.lattice_cases(group)]
    assert len(example_cases)==len(set(example_cases))==276
    assert set(example_cases)=={(name,group,lattice,tuple(iwps))
                               for name,group,lattice,iwps,*_ in reference_cases}
    for group in ('p4*SO(3)','p6*SO(3)','p4m*O(3)','p6m*O(3)'):
        r=classify(group,[],examples/'fibonacci.json')
        assert r['total_realizations']==int('m*' not in group)
